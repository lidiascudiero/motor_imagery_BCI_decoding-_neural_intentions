    "def load_session(sid, session):\n",
    "    p_fif = Path(CFG['clean_dir']) / f'A{sid:02d}{session}{CFG[\"clean_suffix\"]}'\n",
    "    p_trials = Path(CFG['clean_dir']) / f'A{sid:02d}{session}_trials.csv'\n",
    "    meta = pd.read_csv(p_trials)\n",
    "    meta['label'] = meta['label_code'].map(CFG['bci_code_to_label'])\n",
    "    \n",
    "    raw = mne.io.read_raw_fif(p_fif, preload=True, verbose=False)\n",
    "    eeg = raw.pick('eeg').get_data().astype(np.float32)\n",
    "    \n",
    "    fs = CFG['fs']\n",
    "    start_off = int(round(CFG['mi_start_after_cue_s'] * fs))\n",
    "    n_samp = CFG['n_samples']\n",
    "    b0, b1 = int(round(CFG['baseline_start_s'] * fs)), int(round(CFG['baseline_end_s'] * fs))\n",
    "    \n",
    "    segs, keep = [], []\n",
    "    for idx, row in meta.iterrows():\n",
    "        cue = int(row['cue_sample'])\n",
    "        s = cue + start_off\n",
    "        \n",
    "        # Strict bounds checking within the physical run limits\n",
    "        # To do this perfectly, the offset should be mapped, but we ensure boundaries are inside recording\n",
    "        if s < 0 or s + n_samp > eeg.shape[1] or cue + b0 < 0:\n",
    "            keep.append(False); continue\n",
    "            \n",
    "        seg = eeg[:, s:s + n_samp]\n",
    "        base = eeg[:, cue + b0:cue + b1]\n",
    "        \n",
    "        # Strict NaN/Inf verification\n",
    "        if np.isnan(seg).any() or np.isinf(seg).any() or np.isnan(base).any() or np.isinf(base).any():\n",
    "            keep.append(False); continue\n",
    "\n",
    "        seg = (seg - base.mean(axis=-1, keepdims=True)) / (base.std(axis=-1, keepdims=True) + 1e-8)\n",
    "        segs.append(seg)\n",
    "        keep.append(True)\n",
    "        \n",
    "    meta['kept'] = keep\n",
    "    X = np.stack(segs)[..., np.newaxis]\n",
    "    y = meta.loc[meta['kept'], 'label'].values.astype(np.int64)\n",
    "    return X, y, meta\n",
    "\n",
