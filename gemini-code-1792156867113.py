    "# Offline Run-wise Preprocessing with Calibration-Only ICA\n",
    "\n",
    "This preprocessing pipeline for the BCI Competition IV-2a cross-session experiment processes the original GDF files. \n",
    "It uses a calibration-only ICA approach, meaning the ICA is estimated exclusively on the initial calibration runs and frozen before applying it to the motor imagery task runs.\n",
    "\n",
    "**Key Methodological Notes:**\n",
    "- **Not Strictly Causal:** While a minimum-phase FIR filter is used run-by-run, default padding at the edges means strict online/streaming causality is not guaranteed. This is an offline run-wise preprocessing pipeline.\n",
    "- **Calibration:** ICA (20 components, infomax extended) is fitted solely on the calibration blocks (events 276, 277, 1072) which strictly precede the task blocks. \n",
    "- **Provenance & State Isolation:** Cleaned outputs are stored in directories separated by the `ICA_SOURCE_E` configuration to prevent `SKIP_EXISTING` from loading incompatible pipelines."
