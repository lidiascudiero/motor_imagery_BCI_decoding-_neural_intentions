    "def clean_session(sid, session):\n",
    "    name = f'A{sid:02d}{session}'\n",
    "    raw, pos, typ = read_gdf_session(DATA_PATH / f'{name}.gdf')\n",
    "    data, data_start, data_end = split_runs(raw, pos, typ)\n",
    "    table, task_runs = build_trial_table(sid, session, pos, typ, data_start, data_end)\n",
    "\n",
    "    n_runs = len(data_start)\n",
    "    calib_runs = [r for r in range(n_runs) if r not in task_runs]\n",
    "    \n",
    "    # Validate calibration blocks precede tasks\n",
    "    assert len(calib_runs) >= 1, \"No calibration runs found\"\n",
    "    assert max(calib_runs) < min(task_runs), \"Calibration runs must strictly precede task runs\"\n",
    "    \n",
    "    calib_cond = {}\n",
    "    for r in calib_runs:\n",
    "        ev = [CALIB_EVENTS[t] for p, t in zip(pos, typ) if t in CALIB_EVENTS and data_start[r] - GAP <= p <= data_start[r]]\n",
    "        calib_cond[r] = ev[0] if ev else 'unknown'\n",
    "\n",
    "    run_raws = []\n",
    "    for r in range(n_runs):\n",
    "        info = mne.create_info(CH_NAMES, FS, ['eeg'] * 22 + ['eog'] * 3)\n",
    "        rr = mne.io.RawArray(data[:, data_start[r]:data_end[r]], info, verbose=False)\n",
    "        run_raws.append(rr)\n",
    "        \n",
    "    run_f = [r.copy().filter(l_freq=BAND[0], h_freq=BAND[1], phase=FILTER_PHASE, fir_design='firwin', verbose=False) for r in run_raws]\n",
    "\n",
    "    own_fit = (session == 'T') or (ICA_SOURCE_E == 'own_calibration')\n",
    "    if own_fit:\n",
    "        calib_raw = mne.concatenate_raws([run_f[i].copy() for i in calib_runs])\n",
    "        ica = ICA(n_components=N_ICA_COMPONENTS, max_iter='auto', method='infomax', random_state=ICA_SEED, fit_params=dict(extended=True))\n",
    "        ica.fit(calib_raw, verbose=False)\n",
    "        eog_idx, _ = ica.find_bads_eog(calib_raw, ch_name=EOG_NAMES, verbose=False)\n",
    "        ica.exclude = list(eog_idx)\n",
    "        ica.save(OUTPUT_PATH / f'{name}_calibration-ica.fif', overwrite=True)\n",
    "        ica_source = f'{name} calibration runs'\n",
    "        ica_iter = ica.n_iter_\n",
    "        calib_dur = calib_raw.times[-1]\n",
    "    else:\n",
    "        ica = read_ica(OUTPUT_PATH / f'A{sid:02d}T_calibration-ica.fif', verbose=False)\n",
    "        ica_source = f'A{sid:02d}T calibration runs'\n",
    "        ica_iter = \"Loaded from T\"\n",
    "        calib_dur = \"Loaded from T\"\n",
    "\n",
    "    cleaned = []\n",
    "    for r in run_f:\n",
    "        c = r.copy(); ica.apply(c, verbose=False); cleaned.append(c)\n",
    "    raw_clean = mne.concatenate_raws(cleaned)\n",
    "    \n",
    "    raw_clean.set_annotations(raw_clean.annotations + mne.Annotations(\n",
    "        onset=table['cue_sample'].values / FS, duration=0.0,\n",
    "        description=[CLASS_DESC[int(c)] for c in table['label_code']]))\n",
    "    save_path = OUTPUT_PATH / f'{name}{CLEAN_SUFFIX}'\n",
    "    raw_clean.save(save_path, overwrite=True)\n",
    "    table.to_csv(OUTPUT_PATH / f'{name}_trials.csv', index=False)\n",
    "\n",
    "    prov = dict(file=save_path.name, session=session, ica_source=ica_source, \n",
    "                ica_iterations=ica_iter, calibration_duration_s=calib_dur, \n",
    "                excluded_components=list(map(int, ica.exclude)), filter_phase=FILTER_PHASE)\n",
    "    (OUTPUT_PATH / f'{name}_provenance.json').write_text(json.dumps(prov, indent=2))\n",
    "    return prov\n",
    "\n",
    "for sid in SUBJECTS:\n",
    "    for session in SESSIONS:\n",
    "        name = f'A{sid:02d}{session}'\n",
    "        if SKIP_EXISTING and (OUTPUT_PATH / f'{name}{CLEAN_SUFFIX}').exists():\n",
    "            continue\n",
    "        if (DATA_PATH / f'{name}.gdf').exists():\n",
    "            prov = clean_session(sid, session)\n",
    "            print(f\"{name}: ICA fitted on {prov['ica_source']} | Iters: {prov['ica_iterations']} | Dur: {prov['calibration_duration_s']}s | Excluded: {prov['excluded_components']}\")"
